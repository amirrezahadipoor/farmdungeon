const ALIAS = { '\u0625': '\u0627', '\u0671': '\u0627', '\u064a': '\u06cc', '\u0649': '\u06cc', '\u0626': '\u06cc', '\u0643': '\u06a9', '\u0629': '\u0647', '\u0624': '\u0648', '\u2013': '\u2014', '\\': '/', '&': '+', '\u066b': '.' };
const SKIP = /[\u200c\u200d\u200e\u200f\u0640\u064b-\u065f]/g; // نیم‌فاصله/کشیده/اعراب: عرض صفر
const LTR_RUN = /[A-Za-z0-9\u06f0-\u06f9\u0660-\u0669]+(?:[.,:\/%\u00d7x-][A-Za-z0-9\u06f0-\u06f9\u0660-\u0669]+)*/g;
const resolve = (ch) => {
  if (GLYPHS[ch]) return ch;
  if (ALIAS[ch]) return ALIAS[ch];
  const c = ch.charCodeAt(0);
  if (c >= 0x660 && c <= 0x669) return String.fromCharCode(0x6f0 + c - 0x660); // ارقام عربی-هندی → فارسی
  const u = ch.toUpperCase();
  return GLYPHS[u] ? u : ch;
};
// ترتیب نمایش: رشته‌ی فارسی کامل برعکس می‌شود، سپس ردیف‌های ارقام/لاتین دوباره راست‌به‌چپِ-معکوس → خوانا (قبلاً «۱۲۳» → «۳۲۱»)
const prep = (s) => {
  s = String(s).replace(SKIP, '');
  if (!FA.test(s)) return s;
  return [...s].reverse().join('').replace(LTR_RUN, (m) => [...m].reverse().join(''));
};
const H = 9;
const _adv = new Map();
const _mask = new Map();
const _outl = new Map();
const FA = /[؀-ۿ]/;

function glyph(ch) {
  let m = _mask.get(ch);
  if (m === undefined) {
    const rows = (GLYPHS[resolve(ch)] || GLYPHS['?'] || '').split('/');
    const w = rows[0].length || 3;
    m = { w, a: new Uint8Array(w * H) };
    for (let y = 0; y < H; y++) for (let x = 0; x < w; x++) if (rows[y] && rows[y][x] === '#') m.a[y * w + x] = 1;
    _mask.set(ch, m);
    _adv.set(ch, w + 1);
  }
  return m;
}
function outlineMask(ch) {
  let o = _outl.get(ch);
  if (o === undefined) {
    const g = glyph(ch), w = g.w, W2 = w + 2, H2 = H + 2;
    const a = new Uint8Array(W2 * H2);
    for (let y = 0; y < H; y++) for (let x = 0; x < w; x++) if (g.a[y * w + x]) a[(y + 1) * W2 + x + 1] = 2;
    // ن۵۰: سیلاب از لبه‌ی گلیف روی خانه‌های خالی ⇒ «بیرونِ شکل». تنها این خانه‌ها حاشیه
    // می‌گیرند، پس چشمه‌ی بسته‌ی حروف (و/ه/م/ق/ف/ص/ط) پر نمی‌شود و حرف توده‌ی تیره نمی‌گردد.
    const out = new Uint8Array(W2 * H2);
    const st = [];
    const seed = (i) => { if (!a[i] && !out[i]) { out[i] = 1; st.push(i); } };
    for (let x = 0; x < W2; x++) { seed(x); seed((H2 - 1) * W2 + x); }
    for (let y = 0; y < H2; y++) { seed(y * W2); seed(y * W2 + W2 - 1); }
    while (st.length) {
      const i = st.pop(), x = i % W2, y = (i - x) / W2;
      if (y > 0) seed(i - W2);
      if (y < H2 - 1) seed(i + W2);
      if (x > 0) seed(i - 1);
      if (x < W2 - 1) seed(i + 1);
    }
    for (let y = 0; y < H2; y++) for (let x = 0; x < W2; x++) {
      const i = y * W2 + x;
      if (a[i] || !out[i]) continue;
      if ((y > 0 && a[i - W2] === 2) || (y < H2 - 1 && a[i + W2] === 2)
        || (x > 0 && a[i - 1] === 2) || (x < W2 - 1 && a[i + 1] === 2)) a[i] = 1;
    }
    o = { w: W2, a };
    _outl.set(ch, o);
  }
  return o;
}

export function textW(s, sc = 1) {
  s = String(s).replace(SKIP, '');
  let w = 0;
  for (const ch of s) w += (_adv.get(ch) ?? glyph(ch).w + 1);
  return (w - 1) * sc;
}

const _oc = [20, 16, 33, 255];
export function drawText(r, s, x, y, col, sc = 1, o = null) {
  x = Math.round(x); y = Math.round(y);
  s = prep(s);
  const outline = !!(o && o.outline);
  const sh = !!(o && o.shadow);
  const oc = _oc;
  if (outline) oc[3] = col[3] ?? 255;
  let cx = x;
  for (const ch of s) {
    if (outline) {
      const m = outlineMask(ch), w2 = m.w;
      for (let yy = 0; yy < H + 2; yy++) for (let xx = 0; xx < w2; xx++) {
        if (m.a[yy * w2 + xx] === 1) {
          const px = cx - sc + xx * sc, py = y - sc + yy * sc;
          if (sc === 1) r.px(px, py, oc); else r.rect(px, py, sc, sc, oc);
        }
      }
    }
    const g = glyph(ch), w = g.w;
    for (let yy = 0; yy < H; yy++) for (let xx = 0; xx < w; xx++) if (g.a[yy * w + xx]) {
      const px = cx + xx * sc, py = y + yy * sc;
      if (sc === 1) r.px(px, py, col); else r.rect(px, py, sc, sc, col);
    }
    if (sh) for (let xx = 0; xx < w; xx++) {
      let yy = H - 1; while (yy >= 0 && !g.a[yy * w + xx]) yy--;
      if (yy >= 0) { const px = cx + xx * sc, py = y + (yy + 1) * sc; if (sc === 1) r.px(px, py, col); else r.rect(px, py, sc, sc, col); }
    }
    cx += (w + 1) * sc;
  }
}
export function drawTextC(r, s, cx, y, col, sc = 1, o = null) { drawText(r, s, Math.round(cx - textW(s, sc) / 2), y, col, sc, o); }

// ن۵۰: حالتِ عنوان — حاشیه‌ی بیرونیِ یکپارچه + سایه‌ی جدا برای تیترها.
// دو تفاوت با outlineِ drawText: (۱) حاشیه دورِ کلِ رشته کشیده می‌شود، نه دورِ تک‌تکِ حروف
// (پس بینِ حروف نوارِ تیره نمی‌افتد)؛ (۲) سیلاب از لبه‌ی ماسک مشخص می‌کند کدام خانه‌ی خالی
// واقعاً «بیرونِ شکل» است ⇒ چشمه‌ی بسته‌ی حروف (و/ه/م/ق) با حاشیه پر نمی‌شود.
const _tm = new Map();
function titleMask(s, thick) {
  const key = s + '|' + thick;
  let m = _tm.get(key);
  if (m) return m;
  const gs = [...prep(s)].map(glyph);
  const W = gs.reduce((a, g) => a + g.w + 1, 0) + 2 * (thick + 1);
  const Hh = H + 2 * (thick + 1) + 2; // ۲ ردیفِ اضافه برای سایه
  const core = new Uint8Array(W * Hh);
  let cx = thick + 1;
  for (const g of gs) {
    for (let y = 0; y < H; y++) for (let x = 0; x < g.w; x++) if (g.a[y * g.w + x]) core[(y + thick + 1) * W + cx + x] = 1;
    cx += g.w + 1;
  }
  const out = new Uint8Array(W * Hh);
  const st = [];
  const seed = (i) => { if (!core[i] && !out[i]) { out[i] = 1; st.push(i); } };
  for (let x = 0; x < W; x++) { seed(x); seed((Hh - 1) * W + x); }
  for (let y = 0; y < Hh; y++) { seed(y * W); seed(y * W + W - 1); }
  while (st.length) {
    const i = st.pop(), x = i % W, y = (i - x) / W;
    if (y > 0) seed(i - W);
    if (y < Hh - 1) seed(i + W);
    if (x > 0) seed(i - 1);
    if (x < W - 1) seed(i + 1);
  }
  const a = new Uint8Array(W * Hh); // ۳ = هسته، ۲ = حاشیه، ۱ = سایه (همه از جنسِ سیلhouette)
  for (let y = 0; y < Hh; y++) for (let x = 0; x < W; x++) {
    const i = y * W + x;
    if (core[i]) { a[i] = 3; continue; }
    if (!out[i]) continue;
    let d = 9;
    for (let dy = -thick; dy <= thick; dy++) for (let dx = -thick; dx <= thick; dx++) {
      const yy = y + dy, xx = x + dx;
      if (yy < 0 || yy >= Hh || xx < 0 || xx >= W) continue;
      if (core[yy * W + xx]) { const t = Math.max(Math.abs(dx), Math.abs(dy)); if (t < d) d = t; }
    }
    if (d <= thick) a[i] = 2;
  }
  m = { W, H: Hh, a };
  if (_tm.size > 96) _tm.clear(); // تیترها کم‌تعدادند؛ نشت نداریم
  _tm.set(key, m);
  return m;
}

export function drawTitle(r, s, x, y, col, sc = 2, o = null) {
  const thick = Math.max(1, Math.min(2, (o && o.thick) || 1));
  const m = titleMask(String(s), thick);
  const oc = (o && o.oc) || [20, 16, 33, 255];
  const shc = (o && o.shc) || [0, 0, 0, 130];
  const hi = (o && o.hi) || null;
  const dy = (o && o.sh === 0) ? 0 : Math.max(0, (o && o.sh) || 2);
  x = Math.round(x) - (thick + 1) * sc; y = Math.round(y) - (thick + 1) * sc;
  if (dy) for (let yy = 0; yy < m.H; yy++) for (let xx = 0; xx < m.W; xx++) if (m.a[yy * m.W + xx]) {
    const px = x + xx * sc, py = y + (yy + dy) * sc;
    if (sc === 1) r.px(px, py, shc); else r.rect(px, py, sc, sc, shc);
  }
  for (let yy = 0; yy < m.H; yy++) for (let xx = 0; xx < m.W; xx++) {
    const v = m.a[yy * m.W + xx];
    if (!v) continue;
    const px = x + xx * sc, py = y + yy * sc;
    let c = col;
    if (v === 2) c = oc;
    else if (hi && m.a[(yy - 1) * m.W + xx] !== 3) c = hi; // لبه‌ی بالای هر ضربه
    if (sc === 1) r.px(px, py, c); else r.rect(px, py, sc, sc, c);
  }
}
export function drawTitleC(r, s, cx, y, col, sc = 2, o = null) {
  drawTitle(r, s, Math.round(cx - textW(s, sc) / 2), y, col, sc, o);
}
