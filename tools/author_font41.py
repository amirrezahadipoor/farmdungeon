# ن۵۰: نگاشت نویسه‌های بی‌گلیف → نزدیک‌ترین گلیف. فقط نویسه‌هایی که گلیف مستقل ندارند
# (آ/أ/٪/—/→ حالا گلیف واقعی دارند؛ «×» دیگر خودنگاشتِ بی‌اثر نیست)
ALIAS = {
    '\u0625': '\u0627', '\u0671': '\u0627', '\u064a': '\u06cc', '\u0649': '\u06cc',
    '\u0626': '\u06cc', '\u0643': '\u06a9', '\u0629': '\u0647', '\u0624': '\u0648',
    '\u2013': '\u2014', '\\': '/', '&': '+', '\u066b': '.',
}


def _esc(ch):
    if ch == '"': return '\\"'
    if ch == '\\': return '\\\\'
    o = ord(ch)
    if 32 <= o < 127: return ch
    return '\\u%04x' % o


def emit_js():
    """بلوکِ GLYPHS + ALIAS برای js/art/font2.js (تنها بخشِ تولیدیِ آن فایل)"""
    ks = list(G)
    out = ['export const GLYPHS = {']
    for i, k in enumerate(ks):
        out.append('  "%s": "%s"%s' % (_esc(k), '/'.join(G[k]), ',' if i < len(ks) - 1 else ''))
    out.append('};')
    out.append('const ALIAS = { %s };' % ', '.join("'%s': '%s'" % (_esc(a), _esc(b)) for a, b in ALIAS.items()))
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    import sys
    args = sys.argv[1:]
    if args and args[0] == '--emit':
        sys.stdout.write(emit_js()); sys.exit(0)
    if args and args[0] == '--write':
        import re
        p = 'js/art/font2.js'
        src = io.open(p, encoding='utf-8').read()
        pat = re.compile(r'export const GLYPHS = \{.*?\n\};\n(?:[^\n]*\n)*?const ALIAS = \{[^\n]*\};\n', re.S)
        assert len(pat.findall(src)) == 1, 'splice-miss'
        io.open(p, 'w', encoding='utf-8').write(pat.sub(lambda m: emit_js(), src))
        print('wrote %s — %d glyphs, %d aliases' % (p, len(G), len(ALIAS))); sys.exit(0)
    names = args if args else list(G)
    # پیش‌نمایش شبکه‌ای: ۸ گلیف در ردیف
    per = 8
    for i in range(0, len(names), per):
        chunk = names[i:i+per]
        for row in range(9):
            print('  '.join(G[n][row] for n in chunk))
        print('  '.join(n.center(max(len(x) for x in G[n])) for n in chunk))
        print()
